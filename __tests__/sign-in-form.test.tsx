import {act,cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {afterEach,beforeEach,describe,it,expect,vi} from 'vitest'
const {signIn,options}=vi.hoisted(()=>({signIn:vi.fn(),options:{current:undefined as undefined|{workspaceSso:boolean;domain:string|null}}}))
vi.mock('@convex-dev/auth/react',()=>({useAuthActions:()=>({signIn})}))
vi.mock('convex/react',()=>({useQuery:()=>options.current}))
import {SignInForm} from '../src/components/sign-in-form'
beforeEach(()=>{cleanup();signIn.mockReset();signIn.mockResolvedValue({});options.current={workspaceSso:false,domain:null}})
afterEach(()=>{vi.useRealTimers()})
function email(){fireEvent.change(screen.getByLabelText('Email address'),{target:{value:'Person@Example.com'}})}
async function send(){email();fireEvent.click(screen.getByRole('button',{name:'Send verification code'}));await screen.findByLabelText('Verification code')}
describe('welcome and account access',()=>{
 it('explains the product and distinguishes account creation without changing providers',async()=>{
  render(<SignInForm/>)
  expect(screen.getByRole('heading',{name:/Good ideas deserve/})).toBeInTheDocument()
  expect(screen.getByRole('button',{name:'Sign in'})).toHaveAttribute('aria-pressed','true')
  fireEvent.click(screen.getByRole('button',{name:'Create account'}))
  expect(screen.getByRole('heading',{name:'Create your account'})).toBeInTheDocument()
  expect(screen.getByText(/Verify your email to finish setting up your account/)).toBeInTheDocument()
  email();fireEvent.click(screen.getByRole('button',{name:'Create account with email'}))
  await screen.findByLabelText('Verification code')
  expect(signIn).toHaveBeenCalledTimes(1)
  expect(signIn.mock.calls[0][0]).toBe('resend-otp')
  expect(signIn.mock.calls[0][1].get('email')).toBe('person@example.com')
  expect(screen.getByRole('button',{name:'Verify and create account'})).toBeInTheDocument()
 })
 it('submits the code with its verified email context, surfaces an error and retains recovery',async()=>{
  render(<SignInForm/>);await send()
  expect(screen.getByLabelText('Verification code')).toHaveFocus()
  fireEvent.change(screen.getByLabelText('Verification code'),{target:{value:'12x3456'}})
  expect(screen.getByLabelText('Verification code')).toHaveValue('123456')
  signIn.mockRejectedValueOnce(Error('private upstream detail'))
  fireEvent.click(screen.getByRole('button',{name:'Verify and enter'}))
  expect(await screen.findByRole('alert')).toHaveTextContent('invalid or expired')
  expect(screen.getByRole('alert')).not.toHaveTextContent('private upstream detail')
  expect(signIn.mock.calls[1][1].get('email')).toBe('person@example.com')
  expect(signIn.mock.calls[1][1].get('code')).toBe('123456')
  fireEvent.click(screen.getByRole('button',{name:'Use another email'}))
  expect(screen.getByLabelText('Email address')).toHaveValue('person@example.com')
  expect(screen.getByLabelText('Email address')).toHaveFocus()
  expect(screen.queryByRole('alert')).toBeNull()
 })
 it('prevents duplicate email requests and keeps a failed send recoverable',async()=>{
  let release!:()=>void;signIn.mockReturnValueOnce(new Promise<void>(r=>{release=r}))
  render(<SignInForm/>);email()
  const form=screen.getByRole('button',{name:'Send verification code'}).closest('form')!
  fireEvent.submit(form);fireEvent.submit(form)
  expect(signIn).toHaveBeenCalledTimes(1)
  expect(screen.getByRole('button',{name:'Sending…'})).toBeDisabled()
  await act(async()=>release())
  expect(screen.getByLabelText('Verification code')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button',{name:'Use another email'}))
  signIn.mockRejectedValueOnce(Error('private upstream detail'))
  fireEvent.click(screen.getByRole('button',{name:'Send verification code'}))
  expect(await screen.findByRole('alert')).toHaveTextContent('couldn’t send a code')
  expect(screen.getByRole('button',{name:'Send verification code'})).toBeEnabled()
 })
 it('resends only after its cooldown and clears an old code without creating a new email identity',async()=>{
  vi.useFakeTimers();render(<SignInForm/>);email()
  await act(async()=>fireEvent.click(screen.getByRole('button',{name:'Send verification code'})))
  expect(screen.getByRole('button',{name:'Resend code in 30s'})).toBeDisabled()
  fireEvent.change(screen.getByLabelText('Verification code'),{target:{value:'123456'}})
  for(let i=0;i<30;i++)await act(async()=>vi.advanceTimersByTime(1000))
  await act(async()=>fireEvent.click(screen.getByRole('button',{name:'Resend code'})))
  expect(signIn).toHaveBeenCalledTimes(2)
  expect(signIn.mock.calls[1][1].get('email')).toBe('person@example.com')
  expect(signIn.mock.calls[1][1].get('code')).toBeNull()
  expect(screen.getByLabelText('Verification code')).toHaveValue('')
  expect(screen.getByRole('status')).toHaveTextContent('Use the latest email')
 })
 it('recovers the resend countdown after a background tab without sending automatically',async()=>{
  vi.useFakeTimers();vi.setSystemTime(new Date('2026-01-01T00:00:00Z'));render(<SignInForm/>);email()
  await act(async()=>fireEvent.click(screen.getByRole('button',{name:'Send verification code'})))
  expect(screen.getByRole('button',{name:'Resend code in 30s'})).toBeDisabled()
  // Browser timers can be throttled while a tab is hidden; advance the clock without running them.
  vi.setSystemTime(new Date('2026-01-01T00:00:15Z'));fireEvent(document,new Event('visibilitychange'))
  expect(screen.getByRole('button',{name:'Resend code in 15s'})).toBeDisabled()
  vi.setSystemTime(new Date('2026-01-01T00:01:00Z'));fireEvent(window,new Event('focus'))
  expect(screen.getByRole('button',{name:'Resend code'})).toBeEnabled()
  expect(signIn).toHaveBeenCalledTimes(1)
  await act(async()=>fireEvent.click(screen.getByRole('button',{name:'Resend code'})))
  expect(signIn).toHaveBeenCalledTimes(2)
  expect(screen.getByRole('button',{name:'Resend code in 30s'})).toBeDisabled()
 })
 it('offers Workspace only when configured and recovers from a failed organization login',async()=>{
  const {rerender}=render(<SignInForm/>)
  expect(screen.queryByRole('button',{name:/Google Workspace/})).toBeNull()
  options.current={workspaceSso:true,domain:'example.com'};rerender(<SignInForm/>)
  signIn.mockRejectedValueOnce(Error('private organization error'))
  fireEvent.click(screen.getByRole('button',{name:/Google Workspace/}))
  expect(await screen.findByRole('alert')).toHaveTextContent('continue with email')
  await waitFor(()=>expect(screen.getByRole('button',{name:'Send verification code'})).toBeEnabled())
  expect(signIn).toHaveBeenCalledWith('google',{redirectTo:'/'})
 })
})
