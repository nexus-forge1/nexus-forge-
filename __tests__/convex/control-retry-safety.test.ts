// @vitest-environment edge-runtime
import {describe,it,expect,vi,afterEach} from 'vitest'
import {convexTest} from 'convex-test'
import schema from '../../convex/schema'
import {api} from '../../convex/_generated/api'
const modules=import.meta.glob('../../convex/**/*.ts')
afterEach(()=>{vi.clearAllTimers();vi.useRealTimers()})
async function fixture(){
 vi.useFakeTimers()
 const t=convexTest(schema,modules),owner=t.withIdentity({subject:'owner'}),other=t.withIdentity({subject:'other'})
 const missionId=await t.run(ctx=>ctx.db.insert('missions',{ownerKey:'owner',title:'Control retry fixture',mission:'Verify retry safety',autonomy:'governed',budget:0,status:'draft',completion:0,approved:false}))
 const snapshot=()=>t.run(async ctx=>({audits:await ctx.db.query('frontierAudits').collect(),jobs:await ctx.db.system.query('_scheduled_functions').collect()}))
 return{t,owner,other,missionId,snapshot}
}
describe('unchanged control retries',()=>{
 it('retains team audit history on identical membership and sharing retries after ownership checks',async()=>{
  const{t,owner,other,missionId,snapshot}=await fixture()
  const teamId=await owner.mutation(api.forgeTeams.create,{name:'Retry team'})
  const membershipId=await other.mutation(api.forgeTeams.requestJoin,{teamId})
  const member={teamId,membershipId,role:'contributor' as const,status:'active' as const}
  await owner.mutation(api.forgeTeams.setMember,member)
  await owner.mutation(api.forgeTeams.shareMission,{teamId,missionId,allowExecute:false})
  const before=await snapshot()
  await Promise.all(Array.from({length:6},()=>owner.mutation(api.forgeTeams.setMember,member)))
  await Promise.all(Array.from({length:6},()=>owner.mutation(api.forgeTeams.shareMission,{teamId,missionId,allowExecute:false})))
  expect(await snapshot()).toEqual(before)
  await expect(other.mutation(api.forgeTeams.setMember,member)).rejects.toThrow(/permission denied/)
  await expect(other.mutation(api.forgeTeams.shareMission,{teamId,missionId,allowExecute:false})).rejects.toThrow(/permission denied/)
  await expect(t.mutation(api.forgeTeams.setMember,member)).rejects.toThrow(/Authenticated/)
  await owner.mutation(api.forgeTeams.shareMission,{teamId,missionId,allowExecute:true})
  await owner.mutation(api.forgeTeams.setMember,{...member,status:'revoked'})
  expect((await snapshot()).audits).toHaveLength(before.audits.length+2)
 })
 it('does not reschedule an enabled feed or invalidate its in-flight generation',async()=>{
  const{t,owner,other,missionId,snapshot}=await fixture()
  const feedId=await owner.mutation(api.outcomeFeeds.create,{missionId,reportId:'retry-fixture'})
  const initial=await t.run(ctx=>ctx.db.get(feedId)),before=await snapshot()
  await Promise.all(Array.from({length:8},()=>owner.mutation(api.outcomeFeeds.setEnabled,{feedId,enabled:true})))
  expect(await t.run(ctx=>ctx.db.get(feedId))).toEqual(initial)
  expect(await snapshot()).toEqual(before)
  await expect(other.mutation(api.outcomeFeeds.setEnabled,{feedId,enabled:true})).rejects.toThrow(/access denied/)
  await expect(t.mutation(api.outcomeFeeds.setEnabled,{feedId,enabled:true})).rejects.toThrow(/Authenticated/)
  await owner.mutation(api.outcomeFeeds.setEnabled,{feedId,enabled:false})
  expect(await t.run(ctx=>ctx.db.get(feedId))).toMatchObject({enabled:false,generation:2})
  const disabled=await snapshot()
  await owner.mutation(api.outcomeFeeds.setEnabled,{feedId,enabled:false})
  expect(await snapshot()).toEqual(disabled)
  await owner.mutation(api.outcomeFeeds.setEnabled,{feedId,enabled:true})
  expect(await t.run(ctx=>ctx.db.get(feedId))).toMatchObject({enabled:true,generation:3})
  const resumed=await snapshot()
  expect(resumed.jobs).toHaveLength(before.jobs.length+1)
  expect(resumed.audits).toHaveLength(before.audits.length+2)
 })
 it('does not append telemetry audit rows for repeated saved state',async()=>{
  const{t,owner,other,missionId,snapshot}=await fixture()
  const sourceId=await t.run(ctx=>ctx.db.insert('productSources',{ownerKey:'owner',missionId,name:'Retry fixture',tokenHash:'a'.repeat(64),enabled:true,generation:1,received:0,pendingCount:0,pendingSuccess:0,batch:0,createdAt:1}))
  const original=await t.run(ctx=>ctx.db.get(sourceId)),before=await snapshot()
  await Promise.all(Array.from({length:8},()=>owner.mutation(api.productTelemetry.setEnabled,{sourceId,enabled:true})))
  expect(await snapshot()).toEqual(before)
  expect(await t.run(ctx=>ctx.db.get(sourceId))).toEqual(original)
  await expect(other.mutation(api.productTelemetry.setEnabled,{sourceId,enabled:true})).rejects.toThrow(/access denied/)
  await expect(t.mutation(api.productTelemetry.setEnabled,{sourceId,enabled:true})).rejects.toThrow(/Authenticated/)
  await owner.mutation(api.productTelemetry.setEnabled,{sourceId,enabled:false})
  const disabled=await snapshot()
  await owner.mutation(api.productTelemetry.setEnabled,{sourceId,enabled:false})
  expect(await snapshot()).toEqual(disabled)
  await owner.mutation(api.productTelemetry.setEnabled,{sourceId,enabled:true})
  expect((await snapshot()).audits).toHaveLength(before.audits.length+2)
  expect(await t.run(ctx=>ctx.db.get(sourceId))).toEqual(original)
 })
 it('keeps adapter revocation retry safe without weakening access denial',async()=>{
  const{t,owner,other,snapshot}=await fixture()
  const packageId=await owner.mutation(api.frontierControls.registerPackage,{name:'retry-adapter',version:'1.0.0',description:'Retry fixture',inputFields:['query'],outputFields:['answer']})
  await owner.mutation(api.frontierControls.validatePackage,{packageId,input:'{"query":"x"}',output:'{"answer":"y"}'})
  const adapterId=await owner.mutation(api.externalRuntime.register,{packageId,endpoint:'https://example.com/json'})
  const before=await snapshot()
  await owner.mutation(api.externalRuntime.setEnabled,{adapterId,enabled:true})
  expect(await snapshot()).toEqual(before)
  await Promise.all(Array.from({length:8},()=>owner.mutation(api.externalRuntime.setEnabled,{adapterId,enabled:false})))
  const revoked=await snapshot()
  expect(revoked.audits).toHaveLength(before.audits.length+1)
  expect(await t.run(ctx=>ctx.db.get(adapterId))).toMatchObject({enabled:false})
  await expect(other.mutation(api.externalRuntime.setEnabled,{adapterId,enabled:false})).rejects.toThrow(/access denied/)
  await expect(t.mutation(api.externalRuntime.setEnabled,{adapterId,enabled:false})).rejects.toThrow(/Authenticated/)
  expect(await snapshot()).toEqual(revoked)
  await owner.mutation(api.externalRuntime.setEnabled,{adapterId,enabled:true})
  expect((await snapshot()).audits).toHaveLength(before.audits.length+2)
 })
 it('retains exactly one retirement event across concurrent retries and still denies foreign owners',async()=>{
  const{t,owner,other,snapshot}=await fixture()
  const packageId=await owner.mutation(api.frontierControls.registerPackage,{name:'retry-package',version:'1.0.0',description:'Retry fixture',inputFields:['query'],outputFields:['answer']})
  const before=await snapshot()
  await Promise.all(Array.from({length:8},()=>owner.mutation(api.frontierControls.retirePackage,{packageId})))
  const retired=await snapshot()
  expect(retired.audits).toHaveLength(before.audits.length+1)
  expect(retired.audits.filter(r=>r.action==='package-retired')).toHaveLength(1)
  expect(await t.run(ctx=>ctx.db.get(packageId))).toMatchObject({status:'retired'})
  await expect(other.mutation(api.frontierControls.retirePackage,{packageId})).rejects.toThrow(/access denied/)
  await expect(t.mutation(api.frontierControls.retirePackage,{packageId})).rejects.toThrow(/Authenticated/)
  expect(await snapshot()).toEqual(retired)
 })
})
